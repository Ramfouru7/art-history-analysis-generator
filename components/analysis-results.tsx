"use client";

import { useState } from "react";

import type { AnalysisResult, MuseumRecord } from "@/lib/analysis/types";

export function AnalysisResults({ result, onStartOver }: { result: AnalysisResult; onStartOver: () => void }) {
  const { artwork, museum, steps } = result;
  const meta = [artwork.artist, artwork.date, artwork.medium].filter(Boolean).join(" \u00B7 ");
  const context = [artwork.period, artwork.culture].filter(Boolean).join(" \u00B7 ");
  const generatedOn = new Date(result.generatedAt).toLocaleDateString(undefined, { dateStyle: "long" });

  return (
    <>
      <div className="result-head">
        <div>
          <div className="eyebrow">Your analysis</div>
          <h2>{artwork.title}</h2>
          <p>{`${artwork.artist} \u00B7 Four-step analysis`}</p>
        </div>
        <div className="result-actions">
          <button type="button" className="button-secondary" onClick={onStartOver}>
            Generate another analysis
          </button>
          <button type="button" className="print-button" onClick={() => window.print()}>
            {"Print this page \u2197"}
          </button>
        </div>
      </div>
      <div className="result-grid">
        <aside className="artwork-panel" aria-label="Artwork details">
          <figure>
            {museum ? (
              <ArtworkImage key={museum.imageUrl} museum={museum} />
            ) : (
              <div className="artwork-placeholder" aria-hidden="true">
                <span>{artwork.title.charAt(0).toUpperCase() || "A"}</span>
              </div>
            )}
            <figcaption>
              <h3>{artwork.title}</h3>
              <p>{meta}</p>
              {context ? <p>{context}</p> : null}
            </figcaption>
          </figure>
          <SourceNote museum={museum} />
        </aside>
        <div className="steps">
          {steps.map((step) => (
            <article className="step" key={step.key}>
              <div className="step-num">{step.number}</div>
              <h3>{step.title}</h3>
              <p>{step.body}</p>
            </article>
          ))}
        </div>
      </div>
      <p className="notice">
        {museum
          ? `Artwork title, artist, date, and medium come from the ${museum.sourceName} collection record. `
          : "No museum record was matched, so artwork details are based on the AI model\u2019s general knowledge. "}
        {`The analysis text was generated by AI (${result.model}) on ${generatedOn} and has not been independently verified. Please confirm important facts with scholarly sources.`}
      </p>
    </>
  );
}

function SourceNote({ museum }: { museum: MuseumRecord | null }) {
  if (!museum) {
    return (
      <p className="source-note">
        No matching public-domain image was found in The Met or Art Institute of Chicago collections, so no image is
        shown rather than risk displaying the wrong artwork.
      </p>
    );
  }

  return (
    <p className="source-note">
      {"Image: "}
      <a href={museum.objectUrl} target="_blank" rel="noopener noreferrer">
        {museum.sourceName}
        <span className="sr-only"> (opens in a new tab)</span>
      </a>
      {museum.source === "met" ? ", Open Access (Public Domain)" : ", Public Domain"}
      {museum.creditLine ? `. ${museum.creditLine}` : null}
    </p>
  );
}

function ArtworkImage({ museum }: { museum: MuseumRecord }) {
  const [failed, setFailed] = useState(false);

  if (failed) {
    return (
      <div className="artwork-placeholder" role="img" aria-label="Museum image could not be loaded">
        <span>{museum.title.charAt(0).toUpperCase() || "A"}</span>
      </div>
    );
  }

  // Plain <img> so a museum image that fails to load falls back gracefully.
  // eslint-disable-next-line @next/next/no-img-element
  return (
    <img
      className="artwork-image"
      src={museum.imageUrl}
      alt={museum.imageAlt}
      onError={() => setFailed(true)}
      referrerPolicy="no-referrer"
    />
  );
}
